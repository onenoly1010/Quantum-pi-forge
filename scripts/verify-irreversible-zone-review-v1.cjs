const fs=require("fs"),crypto=require("crypto");
const p="receipts/governance/irreversible-zone-review-v1.json";
const fail=(m)=>{console.error("FAIL irreversible-zone-review-v1: "+m);process.exit(1)};
if(!fs.existsSync(p)) fail("missing receipt");
const r=JSON.parse(fs.readFileSync(p,"utf8"));
if(r.schema!=="qpf.irreversible_zone_review.receipt.v1") fail("bad schema");
if(r.status!=="sealed") fail("status not sealed");
if(r.named_action!=="supervised-mainnet-activation-execution-v1") fail("bad named action");
if(r.classification_only!==true) fail("classification_only must be true");
for(const k of ["authorizes_execution","authorizes_wallet_actions","authorizes_private_key_access","authorizes_signing","authorizes_transaction_broadcast","authorizes_deploy","authorizes_stake","authorizes_mint","authorizes_participant_growth","private_key_present","wallet_actions","signing_attempted","transaction_broadcast","live_execution"]) if(r[k]!==false) fail(k+" must be false");
if(!Array.isArray(r.missing_conditions)||r.missing_conditions.length!==0) fail("missing conditions present");
if(!r.review_path||!fs.existsSync(r.review_path)) fail("review missing");
const raw=fs.readFileSync(r.review_path,"utf8");
const actual=crypto.createHash("sha256").update(raw).digest("hex");
if(actual!==r.review_sha256) fail("review sha mismatch");
console.log("PASS irreversible-zone-review-v1");
console.log("STATUS "+r.status);
console.log("NAMED_ACTION "+r.named_action);
console.log("CLASSIFICATION_ONLY true");
console.log("AUTHORIZES_EXECUTION false");
console.log("SATISFIED "+JSON.stringify(r.readiness_conditions_satisfied_by_this_review));
