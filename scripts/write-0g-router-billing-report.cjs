#!/usr/bin/env node

const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');

/**
 * Run health-0g-compute.cjs --json and parse output
 */
function runHealthCheck() {
  return new Promise((resolve, reject) => {
    const scriptPath = path.join(__dirname, 'health-0g-compute.cjs');

    if (!fs.existsSync(scriptPath)) {
      reject(new Error('health-0g-compute.cjs not found'));
      return;
    }

    const child = spawn('node', [scriptPath, '--json'], {
      stdio: ['ignore', 'pipe', 'pipe']
    });

    let stdout = '';
    let stderr = '';

    child.stdout.on('data', (data) => {
      stdout += data.toString();
    });

    child.stderr.on('data', (data) => {
      stderr += data.toString();
    });

    child.on('close', (code) => {
      try {
        const json = JSON.parse(stdout);
        resolve({ json, stderr, exitCode: code });
      } catch (error) {
        reject(new Error(`Failed to parse health check output: ${error.message}`));
      }
    });

    child.on('error', reject);
  });
}

/**
 * Format ISO timestamp for filename and markdown
 */
function getTimestamps() {
  const now = new Date();
  const iso = now.toISOString();
  const filedate = iso.replace(/[:.]/g, '-').split('Z')[0]; // YYYY-MM-DDTHH-mm-ss
  return { iso, filedate };
}

/**
 * Generate markdown report
 */
function generateReport(healthData, timestamps) {
  const routerChat = healthData.ROUTER_CHAT || {};
  const status = routerChat.status || 'UNKNOWN';
  const details = routerChat.details || {};

  const report = `# 0G Router Billing Status Report

**Generated:** ${timestamps.iso}

## Summary

- **Status:** ${status}
- **HTTP Status Code:** ${details.statusCode || 'N/A'}
- **Error Type:** ${details.errorType || 'N/A'}
- **Error Code:** ${details.errorCode || 'N/A'}
- **Error Message:** ${details.errorMessage || 'N/A'}
- **Request ID:** ${details.requestId || 'N/A'}

## Context

This report captures the 0G Compute Router chat/completions endpoint status.
The router is reachable and models are discoverable, but inference requests are blocked at the billing layer.

### Endpoint

- URL: https://router-api.0g.ai/v1/chat/completions
- Model: 0GM-1.0-35B-A3B
- Method: POST

### Status Interpretation

- **PASS:** Request succeeded (HTTP 200)
- **WARN:** Payment required (HTTP 402) — account balance or billing linkage issue
- **FAIL:** Other error (network, 5xx, auth failure, etc.)

## Recommendation

If status is WARN with \`insufficient_balance\` error:
1. Verify account balance on 0G dashboard
2. Confirm API key is linked to billing account
3. Check for pending transactions or holds
4. Contact 0G support with this request_id for investigation

## No Secrets Recorded

This report contains no API keys, bearer tokens, or sensitive credentials.

---

*Generated by: scripts/write-0g-router-billing-report.cjs*
`;

  return report;
}

/**
 * Ensure archive directory exists
 */
function ensureArchiveDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

/**
 * Write report to file
 */
function writeReport(report, timestamps) {
  const archiveDir = path.join(process.env.HOME || '/root', 'archive', '0g-operational-notes');
  ensureArchiveDir(archiveDir);

  const filename = `0G_ROUTER_BILLING_${timestamps.filedate}.md`;
  const filepath = path.join(archiveDir, filename);

  fs.writeFileSync(filepath, report, 'utf8');

  return { filepath, filename };
}

/**
 * Main
 */
async function main() {
  try {
    // Run health check
    console.error('Running health check...');
    const healthResult = runHealthCheck();
    const result = await healthResult;

    if (result.exitCode !== 0 && result.exitCode !== null) {
      console.error(`Warning: health check exited with code ${result.exitCode}`);
    }

    // Extract timestamps
    const timestamps = getTimestamps();

    // Generate report
    const report = generateReport(result.json, timestamps);

    // Write report
    const { filepath, filename } = writeReport(report, timestamps);

    // Output confirmation
    console.error(`Report written to: ${filepath}`);
    console.error(`Filename: ${filename}`);
    console.log(filename);

    process.exit(0);
  } catch (error) {
    console.error(`Error: ${error.message}`);
    process.exit(1);
  }
}

main();
